export function SocialIcons({ socialLinks }: SocialIconsProps) {
  // Filter platforms that have a URL set
  const activePlatforms = platforms.filter(
    (platform) => socialLinks[platform.key] && socialLinks[platform.key]!.trim() !== ''
  );

  if (activePlatforms.length === 0) {
    return null;
  }

  return (
    <div className="flex flex-row items-center justify-center gap-4">
      {activePlatforms.map(({ key, label, Icon }) => (
        <Link
          key={key}
          href={socialLinks[key]!}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label}
          className="text-gray-600 dark:text-gray-400 transition-all duration-200 hover:text-primary hover:scale-110"
        >
          <Icon />
        </Link>
      ))}
    </div>
  );
}
